-- Autostart Applications & Services

hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd --all")
    hl.exec_cmd("gsettings set org.gnome.desktop.wm.preferences button-layout ':'")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface gtk-enable-primary-paste true")
    hl.exec_cmd("hyprpaper")
    hl.exec_cmd("~/.local/bin/apply-wallpaper --restore")
    hl.exec_cmd("quickshell")
    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("wl-paste --type image --watch cliphist store")
    hl.exec_cmd("kdeconnectd")
    hl.exec_cmd("kdeconnect-indicator")
    hl.exec_cmd("hyprpm reload -n")
end)
